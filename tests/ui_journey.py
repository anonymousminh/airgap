import sys, time
from playwright.sync_api import sync_playwright
URL, OUT = sys.argv[1], sys.argv[2]
errors = []
with sync_playwright() as p:
    b = p.chromium.launch(channel="chrome")
    pg = b.new_page(viewport={"width": 1360, "height": 900})
    pg.on("console", lambda m: errors.append(f"console.{m.type}: {m.text}") if m.type in ("error", "warning") else None)
    pg.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    pg.goto(URL, wait_until="networkidle"); pg.wait_for_timeout(2500)
    pg.screenshot(path=f"{OUT}/01-hero.png")
    pg.click("#heroDemo"); pg.wait_for_timeout(900)
    pg.click("#useDemo")                                   # one-click demo
    pg.wait_for_selector("#timeline li.start", timeout=15000); pg.wait_for_timeout(1200)
    pg.screenshot(path=f"{OUT}/02-running.png")
    pg.wait_for_selector("#receiptCard:not([hidden])", timeout=120000); pg.wait_for_timeout(1800)
    pg.locator("#analyst").scroll_into_view_if_needed()
    pg.screenshot(path=f"{OUT}/03-answer-receipt.png", full_page=False)
    pg.locator("#answerCard").screenshot(path=f"{OUT}/03a-answer.png")
    pg.locator("#receiptCard").screenshot(path=f"{OUT}/03b-receipt.png")
    print("answer text:", pg.inner_text("#answer")[:200].replace("\n", " "), "| guard:", pg.inner_text("#guardChip"))
    pg.click(".verify1"); pg.wait_for_timeout(1200)
    print("inline verify:", pg.inner_text(".vr"))
    pg.click(".tamper1"); pg.wait_for_timeout(700)
    t = pg.input_value("#tamperText").replace('"canary_hits_on_listener": 0', '"canary_hits_on_listener": 7')
    pg.fill("#tamperText", t); pg.click("#verifyBtn"); pg.wait_for_timeout(1400)
    pg.screenshot(path=f"{OUT}/04-tampered.png")
    print("tamper verdict:", pg.inner_text("#stamp"), "|", pg.inner_text("#verifyResult")[:90])
    pg.click("#resetTamper"); pg.click("#verifyBtn"); pg.wait_for_timeout(1200)
    print("reset verdict:", pg.inner_text("#stamp"))
    pg.keyboard.press("Escape"); pg.wait_for_timeout(500)
    pg.locator("#lab").scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    pg.click("#runAll")
    pg.wait_for_selector(".tile.running", timeout=10000); pg.wait_for_timeout(400)
    pg.screenshot(path=f"{OUT}/05-lab-running.png")
    pg.wait_for_function("document.querySelectorAll('.tile.contained,.tile.failed').length===6", timeout=120000)
    pg.wait_for_timeout(1800)
    pg.locator("#lab").screenshot(path=f"{OUT}/06-lab-done.png")
    print("scoreboard:", pg.inner_text("#sbContained"), pg.inner_text("#sbBytes"), pg.inner_text("#sbSecrets"))
    pg.locator("#how").scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    pg.locator("#how").screenshot(path=f"{OUT}/07-how.png")
    # mobile
    m = b.new_page(viewport={"width": 390, "height": 844}, device_scale_factor=2)
    m.goto(URL, wait_until="networkidle"); m.wait_for_timeout(1500)
    m.screenshot(path=f"{OUT}/08-mobile-hero.png")
    over = m.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
    print("mobile horizontal overflow px:", over)
    b.close()
print("errors:", errors or "none")
